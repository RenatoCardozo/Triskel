// Gera o SQL de migração MySQL a partir do schema Prisma (DMMF), no mesmo formato do `prisma migrate`.
// Uso: node scripts/gen-migration.mjs <nome>   (grava prisma/migrations/<timestamp>_<nome>/migration.sql)
// Existe porque o binário schema-engine do Prisma não pôde ser baixado no ambiente de desenvolvimento.
// Em máquina com rede, `npx prisma migrate dev` é o caminho oficial e deve resultar em diff vazio.
import { getDMMF } from '@prisma/get-dmmf'
import fs from 'node:fs'
import path from 'node:path'

const name = process.argv[2] || 'init'
const schema = fs.readFileSync('prisma/schema.prisma', 'utf8')
const { datamodel: dm } = await getDMMF({ datamodel: schema })
const q = (s) => '`' + s + '`'
const enums = Object.fromEntries(dm.enums.map((e) => [e.name, e.values.map((v) => v.name)]))

function colType(f) {
  if (f.kind === 'enum') return `ENUM(${enums[f.type].map((v) => `'${v}'`).join(', ')})`
  const nt = f.nativeType && f.nativeType[0]
  switch (f.type) {
    case 'String': return nt === 'Text' ? 'TEXT' : nt === 'LongText' ? 'LONGTEXT' : 'VARCHAR(191)'
    case 'Int': return 'INTEGER'
    case 'Float': return 'DOUBLE'
    case 'Boolean': return 'BOOLEAN'
    case 'DateTime': return nt === 'Date' ? 'DATE' : 'DATETIME(3)'
    case 'Json': return 'JSON'
    default: throw new Error('tipo não suportado ' + f.type)
  }
}
function colDefault(f) {
  const d = f.default
  if (d === undefined || d === null) return ''
  if (typeof d === 'object' && !Array.isArray(d)) {
    if (d.name === 'now') return ' DEFAULT CURRENT_TIMESTAMP(3)'
    return '' // cuid, autoincrement
  }
  if (typeof d === 'boolean') return ` DEFAULT ${d}`
  if (typeof d === 'number') return ` DEFAULT ${d}`
  if (f.kind === 'enum') return ` DEFAULT '${d}'`
  return ` DEFAULT '${String(d).replace(/'/g, "''")}'`
}

const tables = []
const fks = []
for (const m of dm.models) {
  const scal = m.fields.filter((f) => f.kind === 'scalar' || f.kind === 'enum')
  const lines = scal.map((f) => {
    const auto = f.default && f.default.name === 'autoincrement' ? ' AUTO_INCREMENT' : ''
    return `    ${q(f.name)} ${colType(f)} ${f.isRequired ? 'NOT NULL' : 'NULL'}${colDefault(f)}${auto}`
  })
  const idx = dm.indexes.filter((i) => i.model === m.name)
  for (const i of idx.filter((i) => i.type === 'unique')) {
    const cols = i.fields.map((x) => x.name)
    lines.push(`    UNIQUE INDEX ${q(`${m.name}_${cols.join('_')}_key`)}(${cols.map(q).join(', ')})`)
  }
  for (const i of idx.filter((i) => i.type === 'normal')) {
    const cols = i.fields.map((x) => x.name)
    lines.push(`    INDEX ${q(`${m.name}_${cols.join('_')}_idx`)}(${cols.map(q).join(', ')})`)
  }
  const pk = idx.find((i) => i.type === 'id')
  lines.push(`    PRIMARY KEY (${pk.fields.map((x) => q(x.name)).join(', ')})`)
  tables.push(`-- CreateTable\nCREATE TABLE ${q(m.name)} (\n${lines.join(',\n')}\n) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n`)
  for (const f of m.fields.filter((f) => f.kind === 'object' && f.relationFromFields && f.relationFromFields.length)) {
    const target = dm.models.find((x) => x.name === f.type)
    const required = f.relationFromFields.every((n) => m.fields.find((x) => x.name === n).isRequired)
    const od = (f.relationOnDelete || (required ? 'Restrict' : 'SetNull')).replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase().replace('_', ' ')
    fks.push(`-- AddForeignKey\nALTER TABLE ${q(m.name)} ADD CONSTRAINT ${q(`${m.name}_${f.relationFromFields.join('_')}_fkey`)} FOREIGN KEY (${f.relationFromFields.map(q).join(', ')}) REFERENCES ${q(target.name)}(${f.relationToFields.map(q).join(', ')}) ON DELETE ${od} ON UPDATE CASCADE;\n`)
  }
}
const ts = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14)
const dir = path.join('prisma/migrations', `${process.env.MIGRATION_TS || ts}_${name}`)
fs.mkdirSync(dir, { recursive: true })
fs.writeFileSync(path.join(dir, 'migration.sql'), tables.join('\n') + '\n' + fks.join('\n'))
fs.writeFileSync('prisma/migrations/migration_lock.toml', '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "mysql"\n')
console.log('Migração gerada em', dir)
